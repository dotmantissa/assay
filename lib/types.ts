export type Benchmark = {
  id: string;
  name: string;
  dataset_url: string;
  content_hash: string;
  rubric: string;
  sample_size: number;
  scale: number;
  tolerance_bps: number;
  overlap_bps: number;
  item_count: number;
  sampling_rule: string;
  publisher: string;
};
export type Grade = {
  id: string;
  score: number;
  incorrect: boolean;
  reason: string;
  sources?: { url: string; text: string }[];
};
export type Round = {
  number: number;
  commitment_tx: string;
  seed: string;
  sample: number[];
  grades: Grade[];
  status: string;
  challenge_id?: string;
  challenger?: string;
  challenge_successful?: boolean;
  settlement?: string;
  score_bps?: number;
  low_bps?: number;
  high_bps?: number;
  method?: string;
  n?: number;
};
export type Run = {
  id: string;
  benchmark_id: string;
  outputs_url: string;
  outputs_hash: string;
  model: string;
  owner: string;
  status: string;
  round_count: number;
  survived: number;
  excluded: number[];
  score_bps: number | null;
  low_bps?: number;
  high_bps?: number;
  method?: string;
  n?: number;
};
export type Job = {
  id: string;
  owner_id: string;
  kind: "publish" | "submit" | "challenge";
  payload: Record<string, unknown>;
  state: string;
  step: number;
  tx_hash: string | null;
  transactions: string[];
  result_id: string;
  attempts: number;
  lease_token: string;
  error: string | null;
  created_at: string;
};
